"""Render the roadmap model as Markdown.

Markdown rather than PDF. Three reasons, and the third is the one that settles
it: other documents need to link to the roadmap, the claude.ai project reads
`docs/` and cannot read a binary, and a PDF can be made from Markdown by hand
whenever one is wanted. The repository is the reference, so the reference has to
be the format the repository is written in.

Generated, therefore never hand-edited. Both files carry a banner saying so,
and every row links back to the document the fact came from, so the way to
correct the roadmap is to correct that document and regenerate.
"""

from __future__ import annotations

import datetime as _dt
from collections import Counter, defaultdict
from pathlib import Path

import model

def _repo_url() -> str:
    """The GitHub URL of `origin`, for issue and PR links; empty when unknown."""
    import subprocess

    try:
        url = subprocess.run(
            ["git", "-C", str(model.REPO), "remote", "get-url", "origin"],
            capture_output=True, text=True, check=True, timeout=10,
        ).stdout.strip()
    except (subprocess.SubprocessError, OSError):
        return ""
    url = url.removesuffix(".git")
    if url.startswith("git@github.com:"):
        url = "https://github.com/" + url[len("git@github.com:"):]
    return url


REPO_URL = _repo_url()
ROADMAP_DIR = model.REPO / "docs" / "roadmap"

BANNER = (
    "<!-- Generated by tools/roadmap/build.py from the repository's own "
    "artefacts. Never edit this file by hand: correct the document a row "
    "points at and regenerate. -->"
)

STATE_LABEL = {
    model.IN_PROGRESS: "in progress",
    model.OPEN: "open",
    model.WAITING: "waiting",
    model.DONE: "done",
    model.DROPPED: "dropped",
}

LANES = (("Features", "feature"), ("Work packages", "work-package"))


def cell(text: str) -> str:
    """Make text safe for a table cell: no pipes, no newlines, no empties."""
    out = " ".join(model.no_dashes(str(text or "")).split()).replace("|", "\\|")
    return out or " "


def link(item: model.Item) -> str:
    """An item as a Markdown link back to the document or issue it came from."""
    label = cell(item.label)
    if item.kind == "issue":
        return "[%s](%s/issues/%s)" % (label, REPO_URL, item.key[1:])
    if item.path is None:
        return label
    try:
        target = Path("..") / item.path.relative_to(model.REPO / "docs")
    except ValueError:
        return label
    return "[%s](%s)" % (label, target.as_posix())


def _where(item: model.Item) -> str:
    parts = []
    summary = item.summary
    if summary:
        parts.append(cell(summary))
    gate = model.real_gate(item.gate)
    if gate:
        parts.append("**Gate**: " + cell(model.first_sentence(gate, 160)))
    # Join without adding a second full stop: most status sentences already end
    # in one, and ". ".join gave every gated row a ".." in the middle of it.
    joined = ""
    for part in parts:
        if joined:
            joined += " " if joined.endswith((".", "?", "!")) else ". "
        joined += part
    return joined or " "


def _rows(item: model.Item, depth: int = 0) -> list[str]:
    prefix = "&nbsp;&nbsp;" * depth
    if depth and item.slice_of:
        prefix += "(%d of %d) " % item.slice_of
    rows = [
        "| %s%s | `%s` | %s | %s |"
        % (
            prefix,
            link(item),
            cell(item.filename),
            STATE_LABEL.get(item.state, item.state),
            _where(item),
        )
    ]
    for slice_item in item.slices:
        rows.extend(_rows(slice_item, depth + 1))
    return rows


def _lane(title: str, items: list[model.Item]) -> list[str]:
    top = [i for i in items if not i.parent]
    if not top:
        return []
    out = [
        "### %s (%d)" % (title, len(items)),
        "",
        "| Item | File | State | Where it stands |",
        "| --- | --- | --- | --- |",
    ]
    for item in top:
        out.extend(_rows(item))
    out.append("")
    return out


def _epic_section(roadmap: model.Roadmap, epic: model.Epic) -> list[str]:
    homed = [i for i in roadmap.homed(epic) if i.state not in (model.DONE, model.DROPPED)]
    issues = roadmap.issues_for(epic)
    if not homed and not issues:
        return []

    heading = epic.title if epic.is_gate else "Epic %d. %s" % (epic.sequence, epic.title)
    heading = cell(heading)
    out = ["## %s" % heading, ""]
    if epic.completes:
        out += [cell(epic.completes), ""]
    gate = model.real_gate(epic.gate)
    if gate:
        out += ["**Gate**: " + cell(model.first_sentence(gate, 300)), ""]
    out += ["Index: [`%s`](../epics/%s)" % (epic.key, epic.key), ""]

    for title, kind in LANES:
        out += _lane(title, [i for i in homed if i.kind == kind])
    out += _lane("Fixes", issues)
    return out


def upcoming(roadmap: model.Roadmap) -> str:
    outstanding = [i for i in roadmap.items.values() if i.state not in (model.DONE, model.DROPPED)]
    counts = Counter(i.state for i in outstanding)
    live_epics = [e for e in roadmap.epics if e.members or e.issues]

    out = [
        "# Roadmap: Upcoming",
        "",
        BANNER,
        "",
        "**Status**: Generated %s by `tools/roadmap/build.py`. Regenerated after every merge by the `{{SKILL_PREFIX}}-merge` skill."
        % _dt.date.today().isoformat(),
        "**Owner**: generated, nobody. Correct a fact in the document it came from.",
        "**Gate**: none.",
        "",
        "**Outstanding**: %d items across %d epics, plus %d open issues. %s."
        % (
            len(outstanding),
            len(live_epics),
            len(roadmap.issues),
            ", ".join(
                "%d %s" % (counts[state], STATE_LABEL[state])
                for state in (model.IN_PROGRESS, model.OPEN, model.WAITING)
                if counts[state]
            )
            or "nothing outstanding",
        ),
        "",
        "**At a glance**: [every epic in sequence](roadmap-overview.png) and "
        "[what is left before each gate](roadmap-gates.png), drawn from the same "
        "data as this page (sources `roadmap-overview.puml` and `roadmap-gates.puml`).",
        "",
        "![Every epic in sequence](roadmap-overview.png)",
        "",
        "**Items are in the order their epic declares**, taken from its sequence "
        "section where it has one and its items table otherwise, so a lane reads as "
        "build order rather than alphabetically. An item the epic does not mention "
        "cannot be placed and is not shown here at all; it appears under Homed in no "
        "epic. The `File` column is the document on disk, so a row can be opened "
        "without following the link.",
        "",
        "Gates first, then the remaining epics in the sequence set by "
        "[`docs/epics/README.md`](../epics/README.md). Each is split into three lanes: "
        "features, work packages and GitHub fixes. A split feature appears as its parent "
        "with its slices indented beneath in build order.",
        "",
        "**State is derived, not declared.** An item's folder decides it where the folder "
        "says anything, and otherwise it is read from the wording of the document's own "
        "status line. That is a keyword match on prose, so the status line is printed "
        "alongside it: where the two disagree, the sentence is right and the label is wrong.",
        "",
    ]

    gates = [e for e in roadmap.epics if e.is_gate]
    for epic in gates + [e for e in roadmap.epics if not e.is_gate]:
        out += _epic_section(roadmap, epic)

    unhomed = roadmap.unhomed()
    if unhomed:
        out += [
            "## Homed in no epic",
            "",
            "Every outstanding item should sit in the item sections of exactly one epic. "
            "These were found in none, so a gate review that reads the epics folder cannot "
            "see them. Give each a row somewhere, even if that is "
            "[`epic-uncategorised.md`](../epics/epic-uncategorised.md).",
            "",
        ]
        for title, kind in LANES:
            out += _lane(title, [i for i in unhomed if i.kind == kind])

    multiple = roadmap.multiply_homed()
    if multiple:
        out += [
            "## Homed in more than one epic",
            "",
            "An item belongs in one epic's items table and is pointed at from the others "
            "under Related, homed elsewhere. These appear in several, so adding the item "
            "tables up double counts them.",
            "",
            "| Item | File | Epics |",
            "| --- | --- | --- |",
        ]
        for item in multiple:
            out.append(
                "| %s | `%s` | %s |"
                % (link(item), cell(item.filename), ", ".join("`%s`" % e for e in item.epics))
            )
        out.append("")

    return "\n".join(out).rstrip() + "\n"


def completed(roadmap: model.Roadmap) -> str:
    done = roadmap.completed()
    by_month: dict[str, list[model.Item]] = defaultdict(list)
    for item in done:
        by_month[item.merged_at[:7] if item.merged_at else ""].append(item)

    out = [
        "# Roadmap: Completed",
        "",
        BANNER,
        "",
        "**Status**: Generated %s by `tools/roadmap/build.py`. Regenerated after every merge by the `{{SKILL_PREFIX}}-merge` skill."
        % _dt.date.today().isoformat(),
        "**Owner**: generated, nobody.",
        "**Gate**: none.",
        "",
        "**Completed**: %d documents archived. Newest first, by the merge that landed each one."
        % len(done),
        "",
        "The date and pull request come from the commit that added the document to its "
        "archive folder, read from `git log` with rename detection off. That commit is the "
        "merge, because archiving happens on the branch and lands with it.",
        "",
    ]

    for month in sorted((m for m in by_month if m), reverse=True):
        out += [
            "## %s" % month,
            "",
            "| Item | File | Merged | PR |",
            "| --- | --- | --- | --- |",
        ]
        for item in by_month[month]:
            pr = "[#%d](%s/pull/%d)" % (item.merged_pr, REPO_URL, item.merged_pr) if item.merged_pr else " "
            out.append(
                "| %s | `%s` | %s | %s |" % (link(item), cell(item.filename), item.merged_at, pr)
            )
        out.append("")

    orphans = by_month.get("", [])
    if orphans:
        out += [
            "## Merge not found in history",
            "",
            "These sit in an archive folder but no commit adds them there, so the move "
            "predates the current history or arrived by some other route.",
            "",
            "| Item | File |",
            "| --- | --- |",
        ]
        out += ["| %s | `%s` |" % (link(item), cell(item.filename)) for item in orphans]
        out.append("")

    return "\n".join(out).rstrip() + "\n"
