"""Render the roadmap model as PlantUML, for the operator to see the shape at a glance.

Two diagrams, both generated from the same model as `upcoming.md`, so the
picture can never disagree with the table:

- `roadmap-overview.puml`: every epic in sequence, each with a progress bar
  and its counts by state. The question it answers is "where are we".
- `roadmap-gates.puml`: the three gates item by item, in three lanes
  (features, work packages, issues), each card coloured by state. The
  question it answers is "what is left before the next gate".

The `.puml` is the source and is committed; `build.py` renders the PNG beside
it when PlantUML is installed. Like the Markdown, neither is ever edited by
hand: correct the document an item comes from and regenerate.
"""

from __future__ import annotations

import datetime as _dt

import model

# One colour per state, used for cards and the progress bar alike.
STATE_COLOUR = {
    model.DONE: "#81C784",
    model.IN_PROGRESS: "#FFB74D",
    model.OPEN: "#E0E0E0",
    model.WAITING: "#B39DDB",
}
STATE_NAME = {
    model.DONE: "done",
    model.IN_PROGRESS: "in progress",
    model.OPEN: "open",
    model.WAITING: "waiting",
}
ISSUE_COLOUR = "#90CAF9"
BAR_WIDTH = 24
TITLE_LIMIT = 42

HEADER = [
    "' Generated by tools/roadmap/build.py. Never edit by hand: correct the",
    "' document an item comes from and regenerate.",
]

SKIN = [
    "skinparam shadowing false",
    "skinparam defaultFontName Helvetica",
    "skinparam defaultFontSize 12",
    "skinparam rectangleRoundCorner 8",
    "skinparam packageStyle rectangle",
    "skinparam ArrowColor #757575",
]


def _text(value: str, limit: int = TITLE_LIMIT) -> str:
    """Safe inside a quoted PlantUML label, and short enough to fit a card."""
    value = model.no_dashes(value).replace('"', "'").replace("\\", "/").strip()
    if len(value) > limit:
        value = value[: limit - 1].rstrip() + "…"
    return value


def _alias(prefix: str, key: str) -> str:
    return prefix + "_" + "".join(c if c.isalnum() else "_" for c in key)


def _counts(roadmap: model.Roadmap, epic: model.Epic) -> dict[str, int]:
    counts = {state: 0 for state in STATE_COLOUR}
    for item in roadmap.homed(epic):
        if item.state in counts:
            counts[item.state] += 1
    return counts


def _bar(counts: dict[str, int]) -> str:
    """A progress bar of coloured blocks, proportional to the counts."""
    total = sum(counts.values())
    if not total:
        return "<color:#BDBDBD>" + "░" * BAR_WIDTH + "</color>"
    cells, used = [], 0
    states = [s for s in STATE_COLOUR if counts[s]]
    for n, state in enumerate(states):
        width = BAR_WIDTH - used if n == len(states) - 1 else max(1, round(BAR_WIDTH * counts[state] / total))
        used += width
        cells.append("<color:%s>%s</color>" % (STATE_COLOUR[state], "█" * width))
    return "".join(cells)


def _legend(with_issues: bool) -> list[str]:
    rows = ["legend right", "|= State |= |"]
    for state, colour in STATE_COLOUR.items():
        rows.append("| %s |<%s>      |" % (STATE_NAME[state], colour))
    if with_issues:
        rows.append("| GitHub issue |<%s>      |" % ISSUE_COLOUR)
    rows.append("endlegend")
    return rows


def _epic_card(roadmap: model.Roadmap, epic: model.Epic) -> list[str]:
    counts = _counts(roadmap, epic)
    total = sum(counts.values())
    issues = len(roadmap.issues_for(epic))
    label = epic.title if epic.is_gate else "%d. %s" % (epic.sequence, epic.title)
    detail = " · ".join("%d %s" % (counts[s], STATE_NAME[s]) for s in STATE_COLOUR if counts[s])
    lines = [
        "<b>%s</b>" % _text(label, 60),
        _bar(counts),
        "%d item%s%s" % (total, "" if total == 1 else "s", (": " + detail) if detail else ""),
    ]
    if issues:
        lines.append("%d open issue%s" % (issues, "" if issues == 1 else "s"))
    colour = "#FFF8E1" if epic.is_gate else "#FAFAFA"
    border = "line:F9A825;line.bold" if epic.is_gate else "line:9E9E9E"
    return ['rectangle "%s" as %s %s;%s' % ("\\n".join(lines), _alias("E", epic.key), colour, border)]


def _sequence_groups(epics: list[model.Epic]):
    """Split the sequence into the main path, the side tracks and the add-ons."""
    side = model.ALONGSIDE
    path, along, addons, rest = [], [], [], []
    for epic in epics:
        if epic.key in side:
            along.append(epic)
        elif epic.key.startswith("epic-addon-"):
            addons.append(epic)
        elif epic.key == "epic-uncategorised.md":
            rest.append(epic)
        else:
            path.append(epic)
    return path, along, addons, rest


def overview(roadmap: model.Roadmap) -> str:
    today = _dt.date.today().isoformat()
    path, along, addons, rest = _sequence_groups(roadmap.epics)
    out = ["@startuml roadmap-overview", *HEADER, *SKIN, "top to bottom direction"]
    out.append("title Roadmap, every epic in sequence (generated %s)" % today)

    for epic in path:
        out += _epic_card(roadmap, epic)
    out.append('package "Alongside" {')
    for epic in along:
        out += ["  " + line for line in _epic_card(roadmap, epic)]
    out.append("}")
    if addons:
        out.append('package "Add-ons and candidates" as ADDONS {')
        for epic in addons:
            out += ["  " + line for line in _epic_card(roadmap, epic)]
        out.append("}")
    for epic in rest:
        out += _epic_card(roadmap, epic)

    for first, second in zip(path, path[1:]):
        out.append("%s --> %s" % (_alias("E", first.key), _alias("E", second.key)))
    if path and addons:
        out.append("%s --> ADDONS" % _alias("E", path[-1].key))
    # Add-ons in rows of three, so many small cards do not make a tall column.
    for n, epic in enumerate(addons[1:], 1):
        before = addons[n - 1] if n % 3 else addons[n - 3]
        direction = "right" if n % 3 else "down"
        out.append("%s -[hidden]%s- %s" % (_alias("E", before.key), direction, _alias("E", epic.key)))
    if rest and addons:
        out.append("ADDONS -[hidden]down- %s" % _alias("E", rest[0].key))

    out += _legend(with_issues=False)
    out.append("@enduml")
    return "\n".join(out) + "\n"


def _card(alias: str, label: str, colour: str) -> str:
    return 'rectangle "%s" as %s %s' % (label, alias, colour)


def _lane(alias: str, title: str, cards: list[tuple[str, str, str]]) -> list[str]:
    # Every lane package carries its own alias: PlantUML merges packages that
    # share a display name, which put one gate's features inside another.
    if not cards:
        return []
    out = ['  package "%s (%d)" as %s {' % (title, len(cards), alias)]
    for alias, label, colour in cards:
        out.append("    " + _card(alias, label, colour))
    out.append("  }")
    for (first, _, _), (second, _, _) in zip(cards, cards[1:]):
        out.append("  %s -[hidden]down- %s" % (first, second))
    return out


def gates(roadmap: model.Roadmap) -> str:
    today = _dt.date.today().isoformat()
    out = ["@startuml roadmap-gates", *HEADER, *SKIN, "top to bottom direction"]
    out.append("title What is left before each gate (generated %s)" % today)
    gate_epics = [e for e in roadmap.epics if e.is_gate]

    for epic in gate_epics:
        homed = roadmap.homed(epic)
        done = sum(1 for i in homed if i.state == model.DONE)
        left = [i for i in homed if i.state not in (model.DONE, model.DROPPED) and not i.parent]
        name = "%s, %d left, %d done" % (_text(epic.title, 50), len(left) + len(roadmap.issues_for(epic)), done)
        out.append('package "%s" as %s {' % (name, _alias("G", epic.key)))
        lanes = (
            ("Features", "f", [i for i in left if i.kind == "feature"]),
            ("Work packages", "w", [i for i in left if i.kind == "work-package"]),
        )
        for title, suffix, items in lanes:
            cards = [
                (_alias("I", epic.key + i.key), _text(i.label), STATE_COLOUR.get(i.state, "#E0E0E0"))
                for i in items
            ]
            out += _lane(_alias("L" + suffix, epic.key), title, cards)
        # The number goes after the title: a leading "#" is a numbered list in creole.
        issue_cards = [
            (_alias("I", epic.key + i.key), _text(i.label, TITLE_LIMIT - 6) + " " + i.key, ISSUE_COLOUR)
            for i in roadmap.issues_for(epic)
        ]
        out += _lane(_alias("Li", epic.key), "Issues", issue_cards)
        out.append("}")

    for first, second in zip(gate_epics, gate_epics[1:]):
        out.append("%s -[hidden]right- %s" % (_alias("G", first.key), _alias("G", second.key)))
    out += _legend(with_issues=True)
    out.append("@enduml")
    return "\n".join(out) + "\n"
